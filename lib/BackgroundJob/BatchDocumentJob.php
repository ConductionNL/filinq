/**
 * Batch Document Job
 *
 * Background job for processing large document generation batches asynchronously.
 * Dispatched by DocumentService when the batch size exceeds the synchronous
 * limit (>10 objects). Progress is stored in the distributed cache and queryable
 * via GET /api/documents/jobs/{jobId}. Per document-output-destinations-and-
 * bulk-retention, DocumentService::dispatchBulkJob() enforces
 * options.output.mode 'files' before this job is ever queued, so every
 * per-object generation call here stores its output to the initiating
 * user's Files (via DocumentService -> DocumentStorageService) instead of
 * discarding the generated bytes.
 *
 * @category BackgroundJob
 * @package  OCA\Filinq\BackgroundJob
 *
 * @author    Conduction Development Team <info@conduction.nl>
 * @copyright 2026 Conduction B.V.
 * @license   EUPL-1.2 https://joinup.ec.europa.eu/collection/eupl/eupl-text-eupl-12
 *
 * @version GIT: <git_id>
 *
 * @link https://www.filinq.app
 *
 * @spec openspec/changes/document-creatie-sjablonen/tasks.md#task-1
 * @spec openspec/changes/document-output-destinations-and-bulk-retention/specs/document-creatie-sjablonen/spec.md#req-ddob-006
 */

declare(strict_types=1);

namespace OCA\Filinq\BackgroundJob;

use Exception;
use OCA\Filinq\Kernel\Contracts\DocumentServiceInterface;
use OCP\AppFramework\Utility\ITimeFactory;
use OCP\BackgroundJob\QueuedJob;
use Psr\Log\LoggerInterface;

/**
 * Queued job for bulk document generation
 *
 * @category BackgroundJob
 * @package  OCA\Filinq\BackgroundJob
 * @author   Conduction B.V. <info@conduction.nl>
 * @license  EUPL-1.2 https://joinup.ec.europa.eu/collection/eupl/eupl-text-eupl-12
 * @link     https://www.filinq.app
 *
 * @spec openspec/changes/document-creatie-sjablonen/tasks.md#task-1
 */
class BatchDocumentJob extends QueuedJob {
	/**
	 * Constructor for BatchDocumentJob.
	 *
	 * @param ITimeFactory $time Time factory
	 * @param DocumentServiceInterface $documentSvc Document generation service
	 * @param LoggerInterface $logger Logger for error reporting
	 *
	 * @return void
	 */
	public function __construct(
		ITimeFactory $time,
		private readonly DocumentServiceInterface $documentSvc,
		private readonly LoggerInterface $logger,
	) {
		parent::__construct(time: $time);

	}//end __construct()

	/**
	 * Run the batch document generation.
	 *
	 * Processes each object individually. Updates job status after each
	 * object so progress can be tracked via getJobStatus(). Individual
	 * failures do not abort the batch (DCS-043).
	 *
	 * @param array $argument Job arguments containing jobId, templateId,
	 *                        objectIds, and options
	 *
	 * @return void
	 *
	 * @spec openspec/changes/document-creatie-sjablonen/tasks.md#task-1
	 */
	protected function run(mixed $argument): void {
		$jobId = $argument['jobId'] ?? '';
		$templateId = $argument['templateId'] ?? '';
		$objectIds = $argument['objectIds'] ?? [];
		$options = $argument['options'] ?? [];

		if (empty($jobId) === true || empty($templateId) === true) {
			$this->logger->error(
				message: 'BatchDocumentJob: missing required arguments',
				context: ['argument' => $argument]
			);
			return;
		}

		$this->processObjects(
			job: ['jobId' => $jobId, 'templateId' => $templateId, 'options' => $options],
			objectIds: $objectIds
		);

	}//end run()

	/**
	 * Generate a document per object and report the progress after each one.
	 *
	 * @param array{jobId: string, templateId: string, options: array} $job       The job.
	 * @param array                                                    $objectIds Array of object UUIDs
	 *
	 * @return void
	 */
	private function processObjects(array $job, array $objectIds): void {
		$tally = new BatchTally(total: count($objectIds));
		$this->storeProgress(job: $job, progress: $tally->progress(status: 'processing'));

		foreach ($objectIds as $objectId) {
			$tally->record(result: $this->generateFor(job: $job, objectId: $objectId));
			$this->storeProgress(job: $job, progress: $tally->progress(status: 'processing'));
		}

		$finalStatus = 'completed';
		if ($tally->hasErrors() === true) {
			$finalStatus = 'completed_with_errors';
		}

		$this->storeProgress(job: $job, progress: $tally->progress(status: $finalStatus));

	}//end processObjects()

	/**
	 * Generate the document for one object.
	 *
	 * @param array{jobId: string, templateId: string, options: array} $job      The job.
	 * @param mixed                                                    $objectId The object UUID.
	 *
	 * @return array<string, mixed> The object's result row.
	 */
	private function generateFor(array $job, mixed $objectId): array {
		try {
			$result = $this->documentSvc->generateDocument(
				templateId: $job['templateId'],
				dataRefs: $this->dataRefsFor(job: $job, objectId: $objectId),
				options: $job['options']
			);
		} catch (Exception $e) {
			return $this->failureEntry(exception: $e, context: ['objectId' => $objectId, 'templateId' => $job['templateId']]);
		}

		return [
			'objectId' => $objectId,
			'status' => 'success',
			'warnings' => $result['warnings'],
			'fileId' => $result['output']['fileId'] ?? null,
			'path' => $result['output']['path'] ?? null,
		];
	}//end generateFor()

	/**
	 * The single data reference for one object, addressed through the job's register and schema.
	 *
	 * @param array{jobId: string, templateId: string, options: array} $job The job.
	 * @param mixed $objectId The object UUID.
	 *
	 * @return array<int, array<string, mixed>> The data references.
	 */
	private function dataRefsFor(array $job, mixed $objectId): array {
		return [
			[
				'register' => $job['options']['register'] ?? '',
				'schema' => $job['options']['schema'] ?? '',
				'id' => $objectId,
			],
		];
	}//end dataRefsFor()

	/**
	 * Log a failed object and return its error row.
	 *
	 * @param Exception $exception The failure.
	 * @param array{objectId: mixed, templateId: string} $context The object and template ids.
	 *
	 * @return array<string, mixed> The object's error row.
	 */
	private function failureEntry(Exception $exception, array $context): array {
		$this->logger->warning(
			message: 'BatchDocumentJob: failed to generate document for object',
			context: $context + ['error' => $exception->getMessage()]
		);

		return [
			'objectId' => $context['objectId'],
			'status' => 'error',
			'error' => $exception->getMessage(),
		];
	}//end failureEntry()

	/**
	 * Store the job's progress, keeping its options so userId survives for auth checks.
	 *
	 * @param array{jobId: string, templateId: string, options: array} $job      The job.
	 * @param array<string, mixed>                                     $progress The tally's progress.
	 *
	 * @return void
	 */
	private function storeProgress(array $job, array $progress): void {
		$this->documentSvc->updateJobStatus(
			jobId: $job['jobId'],
			status: ['jobId' => $job['jobId']] + $progress + ['options' => $job['options']]
		);

	}//end storeProgress()
}//end class
