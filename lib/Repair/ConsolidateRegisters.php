<?php

/**
 * Consolidates Filinq's five OpenRegister registers into one, MOVING THE ROWS.
 *
 * THIS STEP IS NOT LIKE ITS SIBLINGS. MigrateAppConfigKeys copies key/value
 * pairs; MigrateUserPreferences copies preference rows; a register-slug rename
 * is a one-column UPDATE on one row and re-points nothing. This one physically
 * moves object rows between tables. That is the difference that dictates every
 * safety property below, and it is why it insists on verifying an insert before
 * it deletes anything.
 *
 * WHY ROWS MUST MOVE AT ALL. Measured against a live install rather than
 * assumed: an object is bound to its register by NUMERIC ID, not by slug. Every
 * shard table's `_register` column holds that id, and the tables themselves are
 * named `<prefix>openregister_table_<registerId>_<schemaId>` — OpenRegister
 * composes that name from `$register->getId()` at every call site. So merging
 * five registers into one is NOT a rename: `..._<oldRegisterId>_<schemaId>` and
 * `..._<newRegisterId>_<schemaId>` are two different tables, and nothing
 * relocates a row between them on its own. Ship the consolidated register JSON
 * without this step and the import creates the one register, the app addresses
 * it, and every stored object stays behind in a table nothing reads. Nothing
 * errors. The app simply looks empty.
 *
 * WHY AN `INSERT ... SELECT` IS VIABLE. Both tables are generated by
 * MagicMapper from the SAME schema id, so they carry the same columns. The step
 * checks that rather than trusting it — MagicMapper ADDS columns and never
 * removes them, so a source synced against a newer schema version than the
 * target can carry a column the target lacks, and copying it silently drops
 * that property from every object while every row count reconciles.
 *
 * ORDERING IS LOAD-BEARING, AND IT IS THE OPPOSITE OF MigrateRegisterSlug'S.
 * A slug rename must run BEFORE the register import, so the import finds the
 * row instead of forking a second one. This step must run AFTER the import: the
 * target register `filinq` and its 23 schemas — and therefore the target shard
 * tables — have to EXIST before a row can be inserted into one. It is
 * registered last in both `<post-migration>` and `<install>` for that reason.
 * Where the target table is still absent (the import has not run yet on this
 * install) the pair is SKIPPED and logged, and the next run picks it up. This
 * step never issues DDL: creating a shard table it does not own is how a
 * rollback stops being possible.
 *
 * THE SIX PROPERTIES IT GUARANTEES, each of which has a test:
 *
 *  1. IDEMPOTENT. A completed move leaves the source table empty, so a second
 *     run finds nothing to move and says so.
 *  2. NEVER THROWS. It runs under `<install>`, where an escaping exception
 *     aborts the install and the app never enables at all. Every database call
 *     is wrapped and every failure degrades to "stop", never to "continue".
 *     The catches are on `Throwable`, not on `OCP\DB\Exception`: the interface
 *     documents that one type, but a driver, a connection pool or a stub
 *     underneath it can raise something else entirely, and a repair step that
 *     catches only the documented type is a repair step that catches only the
 *     failures somebody remembered to document.
 *  3. REFUSES ON AMBIGUITY. A uuid that already exists in the target is not
 *     overwritten and not skipped-and-deleted: BOTH rows are left alone and the
 *     conflict is logged. Merging is a decision about data.
 *  4. A FAILED READ IS NOT AN EMPTY RESULT. Every read returns null on failure
 *     and an array on success. An empty array says "nothing to move"; null says
 *     "nothing is known" and stops the step. Conflating the two is precisely
 *     how a migration reports success having moved nothing.
 *  5. NON-DESTRUCTIVE UNTIL VERIFIED. Per batch: INSERT, then count the batch's
 *     uuids back OUT of the target, and only then DELETE them from the source.
 *     A batch that does not reconcile leaves the source intact.
 *  6. ONLY TOUCHES TABLES IT HAS PROVEN ARE OURS. A table name cannot be a
 *     bound parameter, so every name is (a) taken from an `information_schema`
 *     result rather than composed, (b) matched on the `openregister_table_`
 *     MARKER rather than a guessed `oc_` prefix, and (c) shape-checked against
 *     the exact (register, schema) pair immediately before it reaches SQL.
 *
 * WHAT IT DELIBERATELY DOES NOT DO. It does not delete the emptied register
 * rows, so a rollback still finds them; and it does not merge conflicting
 * objects.
 *
 * @category  Repair
 * @package   OCA\Filinq\Repair
 * @author    Conduction Development Team <dev@conduction.nl>
 * @copyright 2026 Conduction B.V.
 * @license   EUPL-1.2 https://joinup.ec.europa.eu/collection/eupl/eupl-text-eupl-12
 * @link      https://conduction.nl
 *
 * SPDX-License-Identifier: EUPL-1.2
 * SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>
 */

declare(strict_types=1);

namespace OCA\Filinq\Repair;

use OCP\Migration\IOutput;
use OCP\Migration\IRepairStep;
use Psr\Log\LoggerInterface;

/**
 * Moves this app's objects out of five registers and into one.
 *
 * THREE CLASSES, AND THE SPLIT IS ALONG THE LINE THAT MATTERS FOR REVIEW.
 * ConsolidateRegistersGateway holds every statement this migration is capable
 * of issuing and nothing else, so the DELETEs can be read in one sitting;
 * ConsolidateRegistersDecisions holds the predicates that authorise them, with
 * no database in sight, so each one can be tested on its own; and this class
 * holds the sequencing that puts the two together. A single class would have
 * mixed all three, which on the riskiest step in the app is the wrong economy.
 *
 * @spec exclude No canonical spec covers the consolidation of Filinq's five
 *  OpenRegister registers into one. Pointing this at an existing spec would
 *  report conformance to a requirement that says nothing about it.
 */
class ConsolidateRegisters implements IRepairStep {

	/**
	 * Every register this app used to declare.
	 *
	 * ALL OF THEM, OR NONE. `templateVersion` objects sit in `templates` while
	 * the `template` objects that own them sit there too, and `signerRecord`
	 * rows point at `signingRequest` rows in the same register. Consolidating
	 * some and not others would leave references crossing a register boundary
	 * the app no longer addresses — the half-migrated state is worse than
	 * either end.
	 *
	 * `docudesk` was added after the first five. It is the register named for
	 * this app's OLD APP ID, and it was initially left out on the grounds that
	 * it was "not one of the five" — which was true and beside the point: it
	 * holds 200 objects of this app's own data, so leaving it standing meant
	 * "five registers into one" quietly shipped an app that owned two. Measured
	 * on the reference instance: consent 20, signing 12, templates 11,
	 * document 162, dossier 57, docudesk 200 — 462 objects in total.
	 *
	 * It is listed LAST on purpose. The first five are this app's own declared
	 * registers and move as a set; `docudesk` is the legacy one, so a partial
	 * failure that stops before it leaves the coherent five already together.
	 *
	 * @var array<int, string>
	 */
	public const SOURCE_SLUGS = [
		'consent',
		'signing',
		'templates',
		'document',
		'dossier',
		'docudesk',
	];

	/**
	 * The single register they collapse into.
	 *
	 * This is the slug `x-openregister.app` names in the register JSON, which is
	 * what ImportHandler's autoCreateRegisterIfApplication() resolves a
	 * `type: application` configuration against — that field IS a register slug,
	 * not an attribution label.
	 *
	 * @var string
	 */
	public const TARGET_SLUG = 'filinq';

	/**
	 * Constructor.
	 *
	 * @param LoggerInterface $logger Logger.
	 * @param ConsolidateRegistersGateway $gateway Every statement this step can issue.
	 * @param ConsolidateRegistersDecisions $decisions The pure predicates.
	 *
	 * @spec exclude No canonical spec covers the consolidation of Filinq's five
	 *  OpenRegister registers into one. Pointing this at an existing spec would
	 *  report conformance to a requirement that says nothing about it.
	 */
	public function __construct(
		private readonly LoggerInterface $logger,
		private readonly ConsolidateRegistersGateway $gateway,
		private readonly ConsolidateRegistersDecisions $decisions = new ConsolidateRegistersDecisions(),
	) {
	}//end __construct()

	/**
	 * Step name shown by `occ maintenance:repair`.
	 *
	 * @return string
	 *
	 * @spec exclude No canonical spec covers the consolidation of Filinq's five
	 *  OpenRegister registers into one. Pointing this at an existing spec would
	 *  report conformance to a requirement that says nothing about it.
	 */
	public function getName(): string {
		return 'Consolidate the five Filinq registers into one';
	}//end getName()

	/**
	 * Move every movable object out of the five registers and into `filinq`.
	 *
	 * Reads first, decides second, writes third. The three reads that gate the
	 * whole step — the register ids, the table list, the target's shards — each
	 * return null on failure and each stop the step, because a step that cannot
	 * see the install must not act on it.
	 *
	 * @param IOutput $output Repair output.
	 *
	 * @return void
	 *
	 * @spec exclude No canonical spec covers the consolidation of Filinq's five
	 *  OpenRegister registers into one. Pointing this at an existing spec would
	 *  report conformance to a requirement that says nothing about it.
	 */
	public function run(IOutput $output): void {
		$plan = $this->preflight(output: $output);
		if ($plan === null) {
			return;
		}

		$tally = ['moved' => 0, 'conflicts' => 0, 'skipped' => 0, 'refused' => 0];

		foreach (self::SOURCE_SLUGS as $slug) {
			$sourceId = $plan['ids'][$slug] ?? null;
			if ($sourceId === null || $sourceId === $plan['targetId']) {
				// Not on this install, or already the target row. Both are the
				// idempotent path, not a failure.
				continue;
			}

			$this->consolidateRegister(
				sourceId: $sourceId,
				targetId: $plan['targetId'],
				names: $plan['names'],
				targetTables: $plan['targetTables'],
				tally: $tally
			);
		}

		$output->info(
			sprintf(
				'ConsolidateRegisters: %d object(s) moved into %s, %d conflict(s) left in place, '
				. '%d pair(s) skipped (no target table yet), %d pair(s) refused.',
				$tally['moved'],
				self::TARGET_SLUG,
				$tally['conflicts'],
				$tally['skipped'],
				$tally['refused']
			)
		);
	}//end run()

	/**
	 * Everything the step must know before it may write anything.
	 *
	 * Returns null when the step must not proceed — an unreadable register
	 * table, or a target register/shard set the import has not created yet.
	 * Both are reported through `$output` before the null comes back, because a
	 * step that stops silently is indistinguishable from one that finished.
	 *
	 * @param IOutput $output Repair output, for the early-return messages.
	 *
	 * @return array{ids: array<string, int>, targetId: int, names: array<int, string>, targetTables: array<int, string>}|null
	 */
	private function preflight(IOutput $output): ?array {
		$ids = $this->gateway->registerIds();
		if ($ids === null) {
			$output->info('ConsolidateRegisters: could not read the register table; nothing moved.');
			return null;
		}

		$targetId = $ids[self::TARGET_SLUG] ?? null;
		if ($targetId === null) {
			// The import has not created the target register yet. Not an error
			// and not a completed migration either — the next run will find it.
			$output->info(
				sprintf(
					'ConsolidateRegisters: target register `%s` does not exist yet; nothing moved.',
					self::TARGET_SLUG
				)
			);
			return null;
		}

		$names = $this->gateway->tableNames();
		if ($names === null) {
			$output->info('ConsolidateRegisters: could not list tables; nothing moved.');
			return null;
		}

		$target = $this->decisions->shardTablesFor(names: $names, registerId: $targetId);
		$this->reportAmbiguous(schemaIds: $target['ambiguous'], registerId: $targetId);

		if ($target['tables'] === []) {
			$output->info(
				sprintf(
					'ConsolidateRegisters: target register `%s` has no shard tables yet; nothing moved.',
					self::TARGET_SLUG
				)
			);
			return null;
		}

		return [
			'ids' => $ids,
			'targetId' => $targetId,
			'names' => $names,
			'targetTables' => $target['tables'],
		];
	}//end preflight()

	/**
	 * Move every (schema) pair of one source register.
	 *
	 * @param int $sourceId The register being emptied.
	 * @param int $targetId The register being filled.
	 * @param array<int, string> $names Every table name the database reported.
	 * @param array<int, string> $targetTables Schema id => target table name.
	 * @param array<string, int> $tally Running totals, mutated in place.
	 *
	 * @return void
	 */
	private function consolidateRegister(
		int $sourceId,
		int $targetId,
		array $names,
		array $targetTables,
		array &$tally,
	): void {
		$source = $this->decisions->shardTablesFor(names: $names, registerId: $sourceId);
		$this->reportAmbiguous(schemaIds: $source['ambiguous'], registerId: $sourceId);
		$tally['refused'] += count($source['ambiguous']);

		foreach ($source['tables'] as $schemaId => $sourceTable) {
			$targetTable = $targetTables[$schemaId] ?? null;
			if ($targetTable === null) {
				// The target register does not hold this schema. It may be a
				// stale shard from a schema this app no longer declares, or the
				// import may simply not have reached it. Either way this step
				// does not create tables, so the pair waits.
				$tally['skipped']++;
				$this->logger->warning(
					'ConsolidateRegisters: no target shard table for this schema; skipping the pair. '
					. 'No table is created here — DDL a repair step does not own makes a rollback impossible.',
					['sourceTable' => $sourceTable, 'schemaId' => $schemaId, 'targetRegister' => $targetId]
				);
				continue;
			}

			$result = $this->movePair(
				sourceTable: $sourceTable,
				targetTable: $targetTable,
				sourceId: $sourceId,
				targetId: $targetId,
				schemaId: $schemaId
			);

			$tally['moved'] += $result['moved'];
			$tally['conflicts'] += $result['conflicts'];
			$tally['refused'] += $result['refused'];
		}
	}//end consolidateRegister()

	/**
	 * Move one (register, schema) pair, insert-verify-delete, batch by batch.
	 *
	 * @param string $sourceTable The table rows leave.
	 * @param string $targetTable The table rows arrive in.
	 * @param int $sourceId The source register id.
	 * @param int $targetId The target register id, written into `_register`.
	 * @param int $schemaId The schema id both tables belong to.
	 *
	 * @return array{moved: int, conflicts: int, refused: int}
	 *
	 * @SuppressWarnings(PHPMD.CyclomaticComplexity) Every branch here is a
	 *  distinct refusal condition; collapsing them would collapse the reasons.
	 * @SuppressWarnings(PHPMD.NPathComplexity) As above.
	 */
	private function movePair(
		string $sourceTable,
		string $targetTable,
		int $sourceId,
		int $targetId,
		int $schemaId,
	): array {
		$none = ['moved' => 0, 'conflicts' => 0, 'refused' => 0];
		$refused = ['moved' => 0, 'conflicts' => 0, 'refused' => 1];

		if ($this->namesAreOurs(
			sourceTable: $sourceTable,
			targetTable: $targetTable,
			sourceId: $sourceId,
			targetId: $targetId,
			schemaId: $schemaId
		) === false
		) {
			return $refused;
		}

		$columns = $this->agreedColumns(sourceTable: $sourceTable, targetTable: $targetTable);
		if ($columns === null) {
			return $refused;
		}

		$sourceUuids = $this->gateway->uuidsIn(table: $sourceTable);
		if ($sourceUuids === null) {
			// A failed read is not an empty table. Stop; do not delete.
			return $refused;
		}

		if ($sourceUuids === []) {
			// Idempotency lives here: a completed move emptied the source.
			return $none;
		}

		$taken = $this->gateway->uuidsPresent(table: $targetTable, uuids: $sourceUuids);
		if ($taken === null) {
			return $refused;
		}

		$split = $this->decisions->partitionUuids(sourceUuids: $sourceUuids, targetUuids: $taken);
		if ($split['conflicts'] !== []) {
			$this->logger->warning(
				'ConsolidateRegisters: uuid(s) already present in the target table; leaving BOTH rows in place. '
				. 'This is either a previous run that inserted and then failed to delete, or two genuinely '
				. 'different objects sharing an identity. Those want opposite treatments and nothing here '
				. 'tells them apart, so neither row is touched. Resolve by hand.',
				[
					'sourceTable' => $sourceTable,
					'targetTable' => $targetTable,
					'uuids' => $split['conflicts'],
				]
			);
		}

		$moved = $this->moveBatches(
			sourceTable: $sourceTable,
			targetTable: $targetTable,
			targetId: $targetId,
			columns: $columns,
			uuids: $split['movable']
		);

		return [
			'moved' => $moved,
			'conflicts' => count($split['conflicts']),
			'refused' => 0,
		];
	}//end movePair()

	/**
	 * Both table names must survive the shape check against their own pair.
	 *
	 * @param string $sourceTable Source table name.
	 * @param string $targetTable Target table name.
	 * @param int $sourceId Source register id.
	 * @param int $targetId Target register id.
	 * @param int $schemaId Schema id.
	 *
	 * @return bool True when both are safe to interpolate.
	 */
	private function namesAreOurs(
		string $sourceTable,
		string $targetTable,
		int $sourceId,
		int $targetId,
		int $schemaId,
	): bool {
		$sourceOk = $this->decisions->isSafeTableName(
			name: $sourceTable,
			registerId: $sourceId,
			schemaId: $schemaId
		);
		$targetOk = $this->decisions->isSafeTableName(
			name: $targetTable,
			registerId: $targetId,
			schemaId: $schemaId
		);

		if ($sourceOk === true && $targetOk === true) {
			return true;
		}

		$this->logger->warning(
			'ConsolidateRegisters: a table name failed the shape check for its own (register, schema) pair; '
			. 'refusing to touch it. A table name cannot be a bound parameter, so an unchecked name is an '
			. 'injection point.',
			['sourceTable' => $sourceTable, 'targetTable' => $targetTable, 'schemaId' => $schemaId]
		);

		return false;
	}//end namesAreOurs()

	/**
	 * The column list both tables agree on, or null when they do not.
	 *
	 * @param string $sourceTable Source table name.
	 * @param string $targetTable Target table name.
	 *
	 * @return array<int, string>|null Columns to carry, `_id` excluded.
	 */
	private function agreedColumns(string $sourceTable, string $targetTable): ?array {
		$sourceColumns = $this->gateway->columnsOf(table: $sourceTable);
		$targetColumns = $this->gateway->columnsOf(table: $targetTable);

		if ($sourceColumns === null || $targetColumns === null) {
			$this->logger->warning(
				'ConsolidateRegisters: could not read the columns of one of the tables; refusing the pair. '
				. 'An unreadable schema is not an empty one.',
				['sourceTable' => $sourceTable, 'targetTable' => $targetTable]
			);
			return null;
		}

		if ($this->decisions->looksLikeShardTable(columns: $sourceColumns) === false
			|| $this->decisions->looksLikeShardTable(columns: $targetColumns) === false
		) {
			$this->logger->warning(
				'ConsolidateRegisters: a table matching the shard-table name pattern is missing `_uuid` or '
				. '`_register`; it is not one of ours whatever its name says. Refusing the pair.',
				['sourceTable' => $sourceTable, 'targetTable' => $targetTable]
			);
			return null;
		}

		$missing = $this->decisions->missingColumns(
			sourceColumns: $sourceColumns,
			targetColumns: $targetColumns
		);

		if ($missing !== []) {
			$this->logger->warning(
				'ConsolidateRegisters: the source table carries column(s) the target does not; refusing the '
				. 'pair. Copying anyway would drop those properties from every migrated object while every '
				. 'row count still reconciled — a data loss no count can catch. Sync the schema first.',
				['sourceTable' => $sourceTable, 'targetTable' => $targetTable, 'columns' => $missing]
			);
			return null;
		}

		return $this->decisions->insertColumns(sourceColumns: $sourceColumns);
	}//end agreedColumns()

	/**
	 * Insert, verify, then delete — one batch at a time.
	 *
	 * The ordering is the whole safety property. A batch whose insert fails, or
	 * whose verification does not reconcile, stops the pair with the source
	 * rows still in place: the migration is then INCOMPLETE, which is
	 * recoverable, rather than PARTIAL, which is not.
	 *
	 * @param string $sourceTable The table rows leave.
	 * @param string $targetTable The table rows arrive in.
	 * @param int $targetId Written into `_register` on the way across.
	 * @param array<int, string> $columns Columns to carry.
	 * @param array<int, string> $uuids The movable uuids.
	 *
	 * @return int How many rows were moved AND confirmed.
	 */
	private function moveBatches(
		string $sourceTable,
		string $targetTable,
		int $targetId,
		array $columns,
		array $uuids,
	): int {
		$moved = 0;

		foreach ($this->decisions->chunk(items: $uuids) as $batch) {
			$inserted = $this->gateway->insertBatch(
				sourceTable: $sourceTable,
				targetTable: $targetTable,
				targetId: $targetId,
				columns: $columns,
				batch: $batch
			);

			if ($inserted === false) {
				$this->logger->warning(
					'ConsolidateRegisters: insert failed; the source rows are untouched and the pair is '
					. 'left incomplete. Re-running is safe.',
					['sourceTable' => $sourceTable, 'targetTable' => $targetTable, 'batch' => count($batch)]
				);
				return $moved;
			}

			$observed = $this->countPresent(table: $targetTable, uuids: $batch);
			if ($this->decisions->reconciled(expected: count($batch), observed: $observed) === false) {
				$this->logger->error(
					'ConsolidateRegisters: the target does not hold every uuid of the batch after the insert; '
					. 'NOT deleting the source rows. The pair is left incomplete and both sides now hold some '
					. 'of these rows; a re-run will report the arrived ones as conflicts.',
					[
						'sourceTable' => $sourceTable,
						'targetTable' => $targetTable,
						'expected' => count($batch),
						'observed' => $observed,
					]
				);
				return $moved;
			}

			if ($this->gateway->deleteBatch(table: $sourceTable, uuids: $batch) === false) {
				$this->logger->error(
					'ConsolidateRegisters: rows were inserted and confirmed but could NOT be deleted from the '
					. 'source. They now exist in BOTH tables. The app reads the target, so no object is lost, '
					. 'but the source copies must be removed by hand: a re-run will see them as conflicts and '
					. 'refuse, by design.',
					['sourceTable' => $sourceTable, 'targetTable' => $targetTable, 'uuids' => $batch]
				);
				return $moved;
			}

			$moved += count($batch);
		}

		return $moved;
	}//end moveBatches()

	/**
	 * How many of these uuids the target holds RIGHT NOW.
	 *
	 * Queried back out of the target rather than taken from the driver's
	 * affected-row count: a driver reporting `n` rows written is a claim, and
	 * this is an observation. The delete that follows is authorised by the
	 * observation alone.
	 *
	 * @param string $table The target table, already shape-checked.
	 * @param array<int, string> $uuids The batch just inserted.
	 *
	 * @return int|null The count, or null when the verification itself failed.
	 */
	private function countPresent(string $table, array $uuids): ?int {
		$found = $this->gateway->uuidsPresent(table: $table, uuids: $uuids);
		if ($found === null) {
			return null;
		}

		return count(array_unique($found));
	}//end countPresent()

	/**
	 * Log the (register, schema) pairs that more than one table name claimed.
	 *
	 * @param array<int, int> $schemaIds The ambiguous schema ids.
	 * @param int $registerId The register they belong to.
	 *
	 * @return void
	 */
	private function reportAmbiguous(array $schemaIds, int $registerId): void {
		if ($schemaIds === []) {
			return;
		}

		$this->logger->warning(
			'ConsolidateRegisters: more than one table name matched the same (register, schema) pair — '
			. 'this happens when one database server hosts two Nextcloud installs with different table '
			. 'prefixes. Picking one by prefix would be a guess, so these pairs are left alone.',
			['registerId' => $registerId, 'schemaIds' => $schemaIds]
		);
	}//end reportAmbiguous()
}//end class
